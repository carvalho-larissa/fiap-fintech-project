COMMENT ON COLUMN T_SF_PARCELA.status              IS 'PENDENTE, PAGA, ATRASADA';

COMMENT ON TABLE  T_SF_META                        IS 'Metas financeiras (sonhos) dos usuários';
COMMENT ON COLUMN T_SF_META.status                 IS 'ATIVA, CONCLUIDA, CANCELADA';

COMMENT ON TABLE  T_SF_APORTE_META                 IS 'Valores guardados para cada meta';
