COMMENT ON COLUMN T_SF_DIVIDA.tx_juros_mensal      IS 'Juros ao mês em fração decimal (0.0299 = 2,99% a.m.)';
COMMENT ON COLUMN T_SF_DIVIDA.status               IS 'EM_DIA, ATRASADA, QUITADA';

