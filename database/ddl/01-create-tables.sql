COMMENT ON TABLE  T_SF_RECEITA                     IS 'Entradas de dinheiro';
COMMENT ON COLUMN T_SF_RECEITA.origem              IS 'SALARIO, FREELANCE, INVESTIMENTO, OUTROS';
COMMENT ON COLUMN T_SF_RECEITA.recorrencia         IS 'UNICA, MENSAL, ANUAL';

COMMENT ON TABLE  T_SF_GASTO                       IS 'Saídas de dinheiro (despesas)';
COMMENT ON COLUMN T_SF_GASTO.tipo                  IS 'FIXO ou VARIAVEL';

