COMMENT ON TABLE  T_SF_CONTA_BANCARIA              IS 'Contas bancárias dos usuários';
COMMENT ON COLUMN T_SF_CONTA_BANCARIA.tipo_conta   IS 'CORRENTE, POUPANCA, PAGAMENTO, SALARIO, INVESTIMENTO';

